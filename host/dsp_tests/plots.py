"""Turn dsp_tests raw output into plots + docs/test-results/dsp_tests.md."""
import glob, os, re, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

raw, out = sys.argv[1], sys.argv[2]
plt.rcParams.update({"figure.dpi": 110, "axes.grid": True, "grid.alpha": .3, "font.size": 9})

def load(p):
    return np.genfromtxt(p, delimiter=",", names=True)

# EQ
fig, axs = plt.subplots(1, 3, figsize=(13, 3.4))
for i, ax in enumerate(axs):
    d = load(f"{raw}/eq_cfg{i}.csv")
    ax.semilogx(d["freq"], d["target_db"], lw=3, alpha=.35, label="analytic RBJ")
    ax.semilogx(d["freq"], d["measured_db"], lw=1, label="measured (engine)")
    ax2 = ax.twinx(); ax2.semilogx(d["freq"], d["measured_db"] - d["target_db"], "r", lw=.7); ax2.set_ylim(-.05, .05)
    ax2.set_ylabel("error dB", color="r")
    ax.set_title(f"EQ config {i}"); ax.set_xlabel("Hz"); ax.set_ylabel("dB")
axs[0].legend(loc="lower left")
fig.tight_layout(); fig.savefig(f"{out}/eq_response.png"); plt.close(fig)

# Reverb
fig, axs = plt.subplots(1, 2, figsize=(12, 3.4))
for p in sorted(glob.glob(f"{raw}/reverb_ir_*.csv")):
    d = load(p); lab = os.path.basename(p)[10:-4]
    e = d["L"] ** 2 + d["R"] ** 2
    sch = np.cumsum(e[::-1])[::-1]
    axs[1].plot(d["t"], 10 * np.log10(sch / sch[0] + 1e-30), label=f"decay {lab}")
    if "2.2" in lab:
        axs[0].plot(d["t"], d["L"], lw=.4, label="L"); axs[0].plot(d["t"], d["R"], lw=.4, alpha=.7, label="R")
axs[0].set_xlim(0, .6); axs[0].set_title("Plate IR (decay 2.2 s, pre-delay 20 ms)"); axs[0].legend()
axs[1].set_ylim(-70, 2); axs[1].set_title("Schroeder decay curves"); axs[1].set_xlabel("s"); axs[1].set_ylabel("dB"); axs[1].legend()
fig.tight_layout(); fig.savefig(f"{out}/reverb.png"); plt.close(fig)

# Delay
fig, axs = plt.subplots(1, 2, figsize=(12, 3.2))
for ax, name in zip(axs, ["delay_ir_sync0_pp0.csv", "delay_ir_sync0_pp1.csv"]):
    d = load(f"{raw}/{name}")
    ax.plot(d["t"], d["L"], lw=.8, label="L"); ax.plot(d["t"], -d["R"], lw=.8, label="R (inverted for clarity)")
    ax.set_title(("Stereo" if "pp0" in name else "Ping-pong") + " delay 250 ms, fb 50 %, impulse into L"); ax.legend(); ax.set_xlabel("s")
fig.tight_layout(); fig.savefig(f"{out}/delay.png"); plt.close(fig)

# Limiter
d = load(f"{raw}/limiter.csv")
fig, ax = plt.subplots(figsize=(10, 3))
ax.plot(d["t"], d["in"], lw=.5, alpha=.5, label="input (+12 dB, scaled)"); ax.plot(d["t"], d["out"], lw=.5, label="output")
ax.axhline(10 ** (-.3 / 20), color="r", lw=.7, ls="--", label="ceiling -0.3 dBFS"); ax.axhline(-10 ** (-.3 / 20), color="r", lw=.7, ls="--")
ax.set_ylim(-1.5, 1.5); ax.legend(loc="upper right"); ax.set_title("Safety limiter: square wave with +12 dB overs")
fig.tight_layout(); fig.savefig(f"{out}/limiter.png"); plt.close(fig)

# Dither
d = load(f"{raw}/dither_hist.csv")
fig, ax = plt.subplots(figsize=(5, 3))
c = d["count"] / d["count"].sum()
ax.bar(d["lsb"], c, label="measured")
ax.plot([-2, -1, 0, 1, 2], [0, 0.0 + 1 / 6, 2 / 3, 1 / 6, 0], "r.-", label="theory (TPDF + rounding)")
ax.set_title("Requantisation error, 24-bit LSB"); ax.legend()
fig.tight_layout(); fig.savefig(f"{out}/dither.png"); plt.close(fig)

# Clicks
rows = [l.split() for l in open(f"{raw}/clicks.txt")]
rows = [r for r in rows if not r[1].startswith(("ui.", "midi.", "net."))]
fig, ax = plt.subplots(figsize=(13, 3.2))
ax.bar(range(len(rows)), [float(r[2]) for r in rows])
ax.axhline(6, color="r", ls="--", lw=.8, label="limit 6 dB")
ax.set_xticks(range(len(rows))); ax.set_xticklabels([r[1] for r in rows], rotation=90, fontsize=6)
ax.set_ylabel("worst HF spike dB"); ax.set_title("Click test: every parameter stepped def→max→min→def"); ax.legend()
fig.tight_layout(); fig.savefig(f"{out}/clicks.png"); plt.close(fig)

# Report
res = [l.strip() for l in open(f"{raw}/results.txt") if l.startswith("RESULT")]
bench = [l.split() for l in open(f"{raw}/results.txt") if l.startswith("BENCHSTAGE")]
with open(f"{out}/dsp_tests.md", "w") as f:
    f.write("# DSP host test results\n\nGenerated by `host/dsp_tests/run.sh`. Every test drives the real engine "
            "(`firmware/components/dsp`) through its public API with the real parameter table.\n\n")
    f.write("| result | test |\n|---|---|\n")
    for r in res:
        m = re.match(r"RESULT (\w+) \| (.*)", r)
        f.write(f"| {m.group(1)} | {m.group(2).replace('|', '/')} |\n")
    f.write("\n## Host stage breakdown (x86, relative share of engine time, all effects on)\n\n| stage | % of engine time |\n|---|---|\n")
    for b in bench:
        f.write(f"| {b[1]} | {b[2]} |\n")
    f.write("\n## Plots\n\n")
    for p in ["eq_response", "reverb", "delay", "limiter", "dither", "clicks"]:
        f.write(f"![{p}]({p}.png)\n\n")
print("report:", f"{out}/dsp_tests.md")
